"""Writes mod/logic.tsv, the logic the mod's in-game logic panel checks against, from the APWorld's own tables
(the same rules the PopTracker pack uses): each check's tier gates, research prerequisites, boss gates, combat
era and comfort level, plus the combat gear per era, the comfort pieces and the boss drops.

    ~/projects/archipelago-0.6.8/.venv/bin/python tools/gen_mod_logic.py ~/projects/archipelago-0.6.8

Like the tracker it doesn't follow every detail of generation (combat gear outside the seed still counts,
a comfort piece's materials count by tier), so it can call a check in logic a little early.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(pathlib.Path(sys.argv[1]).resolve()))
sys.path.insert(0, str(root))

from worlds.AutoWorld import AutoWorldRegister  # noqa: E402

# Archipelago loads an installed valheimapworld.apworld too; use this repo's copy instead.
AutoWorldRegister.world_types.pop("Valheim", None)
import valheimapworld as world  # noqa: E402
from valheimapworld.Locations import location_data_table  # noqa: E402
from valheimapworld.Regions import region_data_table  # noqa: E402

# Tier region -> (items, combat eras) needed to get there, summed along the chain.
region_items, region_combat = {}, {}
_region, _items, _combat = "Menu", [], []
while True:
    region_items[_region], region_combat[_region] = list(_items), list(_combat)
    connections = region_data_table[_region].connections
    if not connections:
        break
    _items += [i for i in connections[0].required_items if i not in _items]
    _region = connections[0].destination
    if _region in world.COMBAT_GATES:
        _combat.append(world.COMBAT_GATES[_region])


def boss_token(token, location=None):
    if token.startswith("kill:"):
        return f"kill:{world.boss_name(token)}"
    # Picking up a boss's own drop: bossdrop (the kill; with boss_items bonus, the received drop works too).
    return f"bossdrop:{token}" if world.DROP_CHECKS.get(location) == token else f"boss:{token}"


rows = [
    "# Generated by tools/gen_mod_logic.py from the APWorld. Do not edit by hand.",
    "# tier  number  needs to get there (|-separated): an item received (a research or boss drop), boss:<Boss>",
    "#   (its drop received; with boss_items bonus, or a boss without a drop item, defeating it works too),",
    "#   kill:<Boss> (defeated), bossdrop:<Boss> (picking up its own drop: defeated, or with bonus its drop",
    "#   received), combat:<era>",
    "# location  name  tier  needs beyond the tier's (the same kinds, comfort:<level>, and altarkey:<Boss> with",
    "#   boss_altar_keys)",
    "# combat  era  armor|weapons|ranged  items (any one)",
    "# comfort  key (comfort group, or the piece's name)  comfort  needs (tier:<n> for its materials' tier, items)",
    "# shelter  needs (comfort only counts under a roof)",
    "# boss  name  trophy check  drop item (or empty)",
]
for region in region_items:
    if region.startswith("Tier"):
        needs = region_items[region] + sorted({boss_token(b) for b in world.REGION_BOSSES[region]})
        needs += [f"combat:{era}" for era in region_combat[region]]
        rows.append("\t".join(["tier", region[len("Tier"):], "|".join(dict.fromkeys(needs))]))
for location in location_data_table:
    name = location.user_friendly_name
    needs = [n for n in world.LOCATION_REQS.get(name, ()) if n not in region_items[location.region]]
    needs += sorted({boss_token(b, name) for b in world.LOCATION_BOSSES[name] - world.REGION_BOSSES[location.region]})
    if name in world.COMBAT_GATES:
        needs.append(f"combat:{world.COMBAT_GATES[name]}")
    if name.startswith(world.COMFORT):
        needs.append(f"comfort:{world.comfort_level(name)}")
    if name in world.ALTAR_GATED:
        needs.append(f"altarkey:{world.ALTAR_GATED[name][:-len("'s Altar Key")]}")
    rows.append("\t".join(["location", name, location.region[len("Tier"):], "|".join(dict.fromkeys(needs))]))
for era, gear in world.COMBAT_ERAS.items():
    for kind in ("armor", "weapons", "ranged"):
        rows.append("\t".join(["combat", era, kind, "|".join(gear[kind])]))
for piece in world.COMFORT_PIECES:
    _, token, comfort, group, items, _, tier = piece
    rows.append("\t".join(["comfort", token if group == "None" else group, str(comfort), "|".join([f"tier:{tier}", *items])]))
rows.append("\t".join(["shelter", "|".join([f"tier:{world.SHELTER[2]}", *world.SHELTER[0]])]))
for boss in world.BOSS_ORDER:
    rows.append("\t".join(["boss", boss, world.BOSS_TROPHIES[boss], world.BOSS_DROP_ITEMS.get(boss, "")]))

(root / "mod" / "logic.tsv").write_text("\n".join(rows) + "\n")
print(f"wrote mod/logic.tsv: {len(location_data_table)} checks")
