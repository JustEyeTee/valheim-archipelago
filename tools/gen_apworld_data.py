"""Regenerates valheimapworld/research_data.py from mod/research.tsv.

The mod only lets a research be crafted once every research in its requiredResearchIDs
column has been received, so the APWorld must use the same prerequisites as logic.
Run from the repo root after editing research.tsv:  python3 tools/gen_apworld_data.py
"""
import csv
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
rows = [r for r in csv.reader(open(root / "mod" / "research.tsv", newline=""), delimiter="\t")
        if r and not r[0].startswith("#")]
name_by_id = {r[1]: r[2] for r in rows}

prereqs = {}
unknown = []
for r in rows:
    ids = [p for p in r[4].split("|") if p]
    unknown += [(r[1], p) for p in ids if p not in name_by_id]
    prereqs[r[2]] = tuple(name_by_id[p] for p in ids if p in name_by_id)
if unknown:
    sys.exit(f"research.tsv names prerequisites that don't exist: {unknown}")

out = ["# Generated by tools/gen_apworld_data.py from mod/research.tsv. Do not edit by hand.",
       "",
       "# Research location -> research items that must be received before it can be crafted.",
       "RESEARCH_PREREQS = {"]
out += [f"    {name!r}: {tuple(reqs)!r}," for name, reqs in prereqs.items()]
out += ["}", ""]
(root / "valheimapworld" / "research_data.py").write_text("\n".join(out))
print(f"wrote {len(prereqs)} researches, {sum(1 for v in prereqs.values() if v)} with prerequisites")
