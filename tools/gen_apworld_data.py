"""Regenerates valheimapworld/research_data.py from mod/research.tsv and
valheimapworld/check_data.py from mod/checks.tsv.

Also writes RESEARCH_KIND, each research's kind column (filled by tools/classify_research.py).
The mod only lets a research be crafted once every research in its requiredResearchIDs
column has been received, so the APWorld must use the same prerequisites as logic.
checks.tsv (obtain, kill and explore checks) is embedded in the mod DLL, so both sides
read the same names.
Run from the repo root after editing either file:  python3 tools/gen_apworld_data.py
"""
import csv
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
rows = [r for r in csv.reader(open(root / "mod" / "research.tsv", newline=""), delimiter="\t")
        if r and not r[0].startswith("#")]
name_by_id = {r[1]: r[2] for r in rows}

prereqs = {}
unknown = []
for r in rows:
    ids = [p for p in r[4].split("|") if p]
    unknown += [(r[1], p) for p in ids if p not in name_by_id]
    prereqs[r[2]] = tuple(name_by_id[p] for p in ids if p in name_by_id)
if unknown:
    sys.exit(f"research.tsv names prerequisites that don't exist: {unknown}")

out = ["# Generated by tools/gen_apworld_data.py from mod/research.tsv. Do not edit by hand.",
       "",
       "# Research location -> research items that must be received before it can be crafted.",
       "RESEARCH_PREREQS = {"]
out += [f"    {name!r}: {tuple(reqs)!r}," for name, reqs in prereqs.items()]
out += ["}", "",
        "# Research -> what it unlocks: equipment, building or material (tools/classify_research.py).",
        "# item_locking decides which kinds are locked (ValheimWorld.free_researches).",
        "RESEARCH_KIND = {"]
kinds = {r[2]: (r[10] if len(r) > 10 else "") for r in rows}
if any(k not in ("equipment", "building", "material") for k in kinds.values()):
    sys.exit("research.tsv has researches without a kind: run tools/classify_research.py")
out += [f"    {name!r}: {kind!r}," for name, kind in kinds.items()]
out += ["}", ""]
(root / "valheimapworld" / "research_data.py").write_text("\n".join(out))
print(f"wrote {len(prereqs)} researches, {sum(1 for v in prereqs.values() if v)} with prerequisites")

checks = []
for r in csv.reader(open(root / "mod" / "checks.tsv", newline=""), delimiter="\t"):
    if not r or r[0].startswith("#"):
        continue
    kind, _, name, tier, requires = r[:5]
    reqs = tuple(q for q in requires.split("|") if q)
    unknown += [(name, q) for q in reqs if q not in prereqs]
    checks.append((kind.capitalize(), name, int(tier), reqs))
if unknown:
    sys.exit(f"checks.tsv requires research items that don't exist: {unknown}")
if len({c[1] for c in checks}) != len(checks):
    sys.exit("checks.tsv has duplicate location names")

out = ["# Generated by tools/gen_apworld_data.py from mod/checks.tsv. Do not edit by hand.",
       "",
       "# (location type, location name, tier, research items it also needs)",
       "CHECKS = ("]
out += [f"    {c!r}," for c in checks]
out += [")", ""]
(root / "valheimapworld" / "check_data.py").write_text("\n".join(out))
print(f"wrote {len(checks)} extra checks")

# Biomes (tools/gen_check_biomes.py): each location's biome, and their order. A goal has checks from its boss's
# biome and the ones before it.
RANKS = {"Meadows": 0, "BlackForest": 1, "Swamp": 2, "Ocean": 2, "Mountain": 3, "Plains": 4, "Mistlands": 5,
         "AshLands": 6, "DeepNorth": 7}
BIOME_NAMES = {"Ashlands": "AshLands", "Black Forest": "BlackForest", "Deep North": "DeepNorth",
               "Mistlands": "Mistlands", "Mountains": "Mountain", "Ocean": "Ocean", "Plains": "Plains", "Swamp": "Swamp"}
biomes, missing = {}, []
for r in csv.reader(open(root / "mod" / "checks.tsv", newline=""), delimiter="\t"):
    if r and not r[0].startswith("#"):
        biomes[r[2]] = r[5] if len(r) > 5 else None
for r in rows:
    biomes[r[2]] = r[11] if len(r) > 11 else None
for r in csv.reader(open(root / "mod" / "trophy_biomes.tsv", newline=""), delimiter="\t"):
    if r and not r[0].startswith("#"):
        biomes[f"Trophy: {r[0]}"] = r[1]
biomes.update({f"Biome: {name}": biome for name, biome in BIOME_NAMES.items()})
missing = [name for name, biome in biomes.items() if biome not in RANKS]
if missing:
    sys.exit(f"locations without a biome (run tools/gen_check_biomes.py): {missing[:10]}")
unlock = {r[0]: r[1] for r in csv.reader(open(root / "mod" / "research_unlock_biomes.tsv", newline=""), delimiter="\t")
          if r and not r[0].startswith("#")}
if set(unlock) != {r[2] for r in rows} or any(b not in RANKS for b in unlock.values()):
    sys.exit("mod/research_unlock_biomes.tsv doesn't match research.tsv (run tools/gen_check_biomes.py)")
out = ["# Generated by tools/gen_apworld_data.py from the biome columns (tools/gen_check_biomes.py). Do not edit by hand.",
       "",
       "BIOME_RANKS = " + repr(RANKS),
       "",
       "# Location -> the earliest biome where it can be done.",
       "LOCATION_BIOMES = {"]
out += [f"    {name!r}: {biome!r}," for name, biome in sorted(biomes.items())]
out += ["}", "",
        "# Research -> the earliest biome where something it unlocks can be made (its item is worth having there).",
        "RESEARCH_UNLOCK_BIOMES = {"]
out += [f"    {name!r}: {biome!r}," for name, biome in unlock.items()]
out += ["}", ""]
(root / "valheimapworld" / "biome_data.py").write_text("\n".join(out))
print(f"wrote {len(biomes)} location biomes")

