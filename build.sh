#!/usr/bin/env bash
# Builds the mod from source and packages a test release into dist/:
#   dist/ValheimArchipelagoRandomizer-<commit>.zip
#     BepInEx/plugins/...      -> extract into the Valheim game folder. The mod reads
#                                 research.tsv/trophies.tsv from the plugins folder itself,
#                                 so these files must not go in a subfolder.
#     valheimapworld.apworld   -> install with the Archipelago Launcher
# Newtonsoft.Json.dll is upstream's file as shipped; the game loads its own copy first.
#
# FAST_TEST=1 ./build.sh makes a playtest build (zip name ends in -fasttest): every research
# costs 1 of each ingredient and the Research Bench costs 1 Wood + 1 Stone. The APWorld is
# unaffected, so the same generated room works with either build.
set -euo pipefail
cd "$(dirname "$0")"
export DOTNET_NOLOGO=1 DOTNET_CLI_TELEMETRY_OPTOUT=1
fast=${FAST_TEST:-0}

# --no-incremental: FastTest only changes a define, which incremental builds don't notice.
dotnet build src/ValheimRandomizer.csproj -c Release -nologo -v quiet --no-incremental \
  -p:FastTest=$([ "$fast" = 1 ] && echo true || echo false)
out=src/bin/Release/netstandard2.1
tag=$(git rev-parse --short HEAD)$(git diff --quiet HEAD -- mod src valheimapworld || echo -dirty)
[ "$fast" = 1 ] && tag+=-fasttest
stage=dist/stage
rm -rf "$stage" && mkdir -p "$stage/BepInEx/plugins"
cp "$out/ValheimRandomizer.dll" "$out/Archipelago.MultiClient.Net.dll" \
   mod/Newtonsoft.Json.dll mod/research.tsv mod/trophies.tsv \
   "$stage/BepInEx/plugins/"
if [ "$fast" = 1 ]; then
  # researchRecipeRequirements (6th column) is Item:Amount|Item:Amount; set every amount to 1
  python3 -I - "$stage/BepInEx/plugins/research.tsv" <<'EOF'
import sys
p = sys.argv[1]
lines = open(p, newline="").read().split("\n")
for i, line in enumerate(lines):
    if not line or line.startswith("#"):
        continue
    cols = line.split("\t")
    if len(cols) > 5 and cols[5].strip():
        cols[5] = "|".join(t.split(":")[0] + ":1" if t else t for t in cols[5].split("|"))
        lines[i] = "\t".join(cols)
open(p, "w", newline="").write("\n".join(lines))
EOF
fi
# The source manifest has no container fields (apworld specification.md); the .apworld gets
# version and compatible_version (APContainer scheme 7) when packaged.
(cd valheimapworld && rm -f ../dist/stage/valheimapworld.apworld &&
  mkdir -p ../dist/stage/apw/valheimapworld && cp -r ./*.py archipelago.json docs ../dist/stage/apw/valheimapworld/ &&
  python3 -I -c 'import json, sys; p = sys.argv[1]; m = json.load(open(p)); m.update(version=7, compatible_version=7); json.dump(m, open(p, "w"), indent=2)' \
    ../dist/stage/apw/valheimapworld/archipelago.json &&
  cd ../dist/stage/apw && python3 -I -m zipfile -c ../valheimapworld.apworld valheimapworld) && rm -rf "$stage/apw"
zip="dist/ValheimArchipelagoRandomizer-$tag.zip"
cp LICENSE README.md THIRD_PARTY_NOTICES.md "$stage/" && cp docs/Valheim.yaml "$stage/Valheim-template.yaml"
rm -f "$zip" && (cd "$stage" && python3 -I -m zipfile -c "../$(basename "$zip")" BepInEx valheimapworld.apworld \
  LICENSE README.md THIRD_PARTY_NOTICES.md Valheim-template.yaml)
echo "$zip"

# PopTracker pack (generated by tools/gen_poptracker.py, which needs Archipelago's Python).
if [ -d poptracker ]; then
  if ! grep -q "\"package_version\": \"$(python3 -I -c 'import json; print(json.load(open("valheimapworld/archipelago.json"))["world_version"])')\"" poptracker/manifest.json; then
    echo "warning: poptracker/ is from another APWorld version; rerun tools/gen_poptracker.py" >&2
  fi
  pack="dist/ValheimArchipelagoPopTracker-$tag.zip"
  rm -f "$pack" && (cd poptracker && python3 -I -m zipfile -c "../$pack" ./*)
  echo "$pack"
fi

# Thunderstore package: manifest.json, icon.png, README.md and CHANGELOG.md at the root, plus the mod's
# files (mod managers install them into BepInEx/plugins/<team>-ValheimArchipelago/). The version in
# thunderstore/manifest.json must match the APWorld's world_version.
world_version=$(python3 -I -c 'import json; print(json.load(open("valheimapworld/archipelago.json"))["world_version"])')
ts_version=$(python3 -I -c 'import json; print(json.load(open("thunderstore/manifest.json"))["version_number"])')
[ "$world_version" = "$ts_version" ] || echo "warning: thunderstore/manifest.json is $ts_version, APWorld is $world_version" >&2
ts="$stage/thunderstore" && rm -rf "$ts" && mkdir -p "$ts"
cp thunderstore/manifest.json thunderstore/icon.png README.md CHANGELOG.md LICENSE THIRD_PARTY_NOTICES.md "$ts/"
cp "$stage"/BepInEx/plugins/* "$stage/valheimapworld.apworld" "$ts/"
tszip="dist/ValheimArchipelago-Thunderstore-$tag.zip"
rm -f "$tszip" && (cd "$ts" && python3 -I -m zipfile -c "../../$(basename "$tszip")" ./*)
echo "$tszip"
